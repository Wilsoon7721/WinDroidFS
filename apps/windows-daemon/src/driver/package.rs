use std::ffi::c_void;
use std::fs;
use std::mem::size_of;
use std::path::{Path, PathBuf};
use std::ptr::{null, null_mut};

use super::DriverError;

fn to_wide(s: &str) -> Vec<u16> {
    s.encode_utf16().chain(Some(0)).collect()
}

fn last_error(call: &'static str) -> DriverError {
    DriverError::Win32 {
        call,
        code: unsafe { GetLastError() },
    }
}

pub fn ensure_winusb_package(vid: u16, pid: u16, description: &str) -> Result<String, DriverError> {
    let work_dir = std::env::temp_dir().join(format!("windroidfs_pkg_{vid:04x}_{pid:04x}"));
    let _ = fs::remove_dir_all(&work_dir);
    fs::create_dir_all(&work_dir)?;

    let stem = format!("windroidfs_{vid:04x}_{pid:04x}");
    let inf_name = format!("{stem}.inf");
    let cat_name = format!("{stem}.cat");
    let inf_path = work_dir.join(&inf_name);
    let cat_path = work_dir.join(&cat_name);

    let result = (|| -> Result<String, DriverError> {
        // Write the INF file
        let inf_contents = render_winusb_inf(vid, pid, description, &inf_name, &cat_name);
        fs::write(&inf_path, inf_contents.as_bytes())?;

        // Create the unsigned .cat file with the INF's Authenticode hash
        let hwid_lower = format!("usb\\vid_{vid:04x}&pid_{pid:04x}");
        create_cat_file(&cat_path, &inf_path, &inf_name, &hwid_lower)?;

        // Create an ephemeral self-signed cert, trust it, sign the .cat, and destroy the key
        let subject = format!("CN=USB\\VID_{vid:04X}&PID_{pid:04X} (WinDroidFS autogenerated)");
        self_sign_cat_file(&cat_path, &subject)?;

        // Stage the signed package into the driver store
        stage_inf_into_store(&inf_path, &work_dir)
    })();

    let _ = fs::remove_dir_all(&work_dir);
    result
}

