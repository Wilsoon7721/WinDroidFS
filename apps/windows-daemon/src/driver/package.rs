fn create_cat_file(
    cat_path: &Path,
    inf_path: &Path,
    inf_file_name: &str,
    hwid_lower: &str,
) -> Result<(), DriverError> {
    let hash = calc_authenticode_sha1(inf_path)?;

    let mut hex_tag = String::with_capacity(hash.len() * 2);
    for b in &hash {
        use std::fmt::Write;
        let _ = write!(&mut hex_tag, "{b:02X}");
    }
    let mut wsz_hash = to_wide(&hex_tag);

    let mut h_prov: usize = 0;
    if unsafe {
        CryptAcquireContextW(
            &mut h_prov,
            null(),
            null(),
            PROV_RSA_AES,
            CRYPT_VERIFYCONTEXT,
        )
    } == 0
    {
        return Err(last_error("CryptAcquireContextW(VERIFYCONTEXT)"));
    }

    let mut cat_wide = to_wide(&cat_path.to_string_lossy());
    let h_cat = unsafe {
        CryptCATOpen(
            cat_wide.as_mut_ptr(),
            CRYPTCAT_OPEN_CREATENEW,
            h_prov,
            CRYPTCAT_VERSION_1,
            0x00010001, // szOID_OIWSEC_sha1
        )
    };
    if h_cat.is_null() || h_cat as isize == -1 {
        unsafe { CryptReleaseContext(h_prov, 0) };
        return Err(last_error("CryptCATOpen"));
    }

    let res = (|| -> Result<(), DriverError> {
        let os_attr = "2:6.0,2:6.1,2:6.2,2:6.3,2:10.0";
        put_cat_attr(h_cat, "OS", os_attr)?;
        put_cat_attr(h_cat, "HWID1", hwid_lower)?;

        // Encode SPC_LINK into ASN.1 bytes for SIP_INDIRECT_DATA
        let obsolete = to_wide("<<<Obsolete>>>");
        let spc_link = SpcLink {
            dw_link_choice: SPC_FILE_LINK_CHOICE,
            _pad: 0,
            pwsz_file: obsolete.as_ptr(),
            _union_pad: [0; 3],
        };

        let mut encoded_len = 0u32;
        unsafe {
            CryptEncodeObject(
                X509_ASN_ENCODING | PKCS_7_ASN_ENCODING,
                SPC_CAB_DATA_STRUCT,
                &spc_link as *const _ as *const c_void,
                null_mut(),
                &mut encoded_len,
            )
        };
        if encoded_len == 0 {
            return Err(last_error("CryptEncodeObject(SPC_CAB_DATA_STRUCT size)"));
        }
        let mut encoded_link = vec![0u8; encoded_len as usize];
        if unsafe {
            CryptEncodeObject(
                X509_ASN_ENCODING | PKCS_7_ASN_ENCODING,
                SPC_CAB_DATA_STRUCT,
                &spc_link as *const _ as *const c_void,
                encoded_link.as_mut_ptr(),
                &mut encoded_len,
            )
        } == 0
        {
            return Err(last_error("CryptEncodeObject(SPC_CAB_DATA_STRUCT)"));
        }

        let mut hash_copy = hash;
        let mut sip_data = SipIndirectData {
            data: CryptAttributeTypeValue {
                psz_obj_id: b"1.3.6.1.4.1.311.2.1.25\0".as_ptr() as *mut i8, // SPC_CAB_DATA_OBJID
                value: CryptoApiBlob {
                    cb_data: encoded_len,
                    pb_data: encoded_link.as_mut_ptr(),
                },
            },
            digest_algorithm: CryptAlgorithmIdentifier {
                psz_obj_id: b"1.3.14.3.2.26\0".as_ptr() as *mut i8, // szOID_OIWSEC_sha1
                parameters: CryptoApiBlob {
                    cb_data: 0,
                    pb_data: null_mut(),
                },
            },
            digest: CryptoApiBlob {
                cb_data: hash_copy.len() as u32,
                pb_data: hash_copy.as_mut_ptr(),
            },
        };

        // CRYPT_SUBJTYPE_FLAT_IMAGE: {DE351A42-8E59-11D0-8C47-00C04FC295EE}
        let mut flat_guid = Guid {
            data1: 0xde351a42,
            data2: 0x8e59,
            data3: 0x11d0,
            data4: [0x8c, 0x47, 0x00, 0xc0, 0x4f, 0xc2, 0x95, 0xee],
        };

        let member = unsafe {
            CryptCATPutMemberInfo(
                h_cat,
                null_mut(),
                wsz_hash.as_mut_ptr(),
                &mut flat_guid,
                0x200,
                size_of::<SipIndirectData>() as u32,
                &mut sip_data as *mut _ as *mut u8,
            )
        };
        if member.is_null() {
            return Err(last_error("CryptCATPutMemberInfo"));
        }

        put_member_attr(h_cat, member, "File", &inf_file_name.to_ascii_lowercase())?;
        put_member_attr(h_cat, member, "OSAttr", os_attr)?;

        if unsafe { CryptCATPersistStore(h_cat) } == 0 {
            return Err(last_error("CryptCATPersistStore"));
        }
        Ok(())
    })();

    unsafe {
        CryptCATClose(h_cat);
        CryptReleaseContext(h_prov, 0);
    }
    res
}

fn calc_authenticode_sha1(path: &Path) -> Result<Vec<u8>, DriverError> {
    let path_wide = to_wide(&path.to_string_lossy());
    let h_file = unsafe {
        CreateFileW(
            path_wide.as_ptr(),
            GENERIC_READ,
            FILE_SHARE_READ,
            null(),
            OPEN_EXISTING,
            0,
            null_mut(),
        )
    };
    if h_file == INVALID_HANDLE_VALUE {
        return Err(last_error("CreateFileW(inf)"));
    }

    let mut h_cat_admin: *mut c_void = null_mut();
    if unsafe { CryptCATAdminAcquireContext(&mut h_cat_admin, null(), 0) } == 0 {
        unsafe { CloseHandle(h_file) };
        return Err(last_error("CryptCATAdminAcquireContext"));
    }

    let mut hash_len = 0u32;
    unsafe { CryptCATAdminCalcHashFromFileHandle(h_file, &mut hash_len, null_mut(), 0) };
    if hash_len == 0 {
        unsafe {
            CryptCATAdminReleaseContext(h_cat_admin, 0);
            CloseHandle(h_file);
        }
        return Err(last_error("CryptCATAdminCalcHashFromFileHandle(size)"));
    }

    let mut hash = vec![0u8; hash_len as usize];
    let ok =
        unsafe { CryptCATAdminCalcHashFromFileHandle(h_file, &mut hash_len, hash.as_mut_ptr(), 0) };
    unsafe {
        CryptCATAdminReleaseContext(h_cat_admin, 0);
        CloseHandle(h_file);
    }
    if ok == 0 {
        return Err(last_error("CryptCATAdminCalcHashFromFileHandle"));
    }
    hash.truncate(hash_len as usize);
    Ok(hash)
}

fn put_cat_attr(h_cat: *mut c_void, name: &str, value: &str) -> Result<(), DriverError> {
    let mut name_w = to_wide(name);
    let mut val_w = to_wide(value);
    let attr = unsafe {
        CryptCATPutCatAttrInfo(
            h_cat,
            name_w.as_mut_ptr(),
            CRYPTCAT_ATTR_AUTHENTICATED | CRYPTCAT_ATTR_NAMEASCII | CRYPTCAT_ATTR_DATAASCII,
            (val_w.len() * 2) as u32,
            val_w.as_mut_ptr() as *mut u8,
        )
    };
    if attr.is_null() {
        Err(last_error("CryptCATPutCatAttrInfo"))
    } else {
        Ok(())
    }
}

fn put_member_attr(
    h_cat: *mut c_void,
    member: *mut c_void,
    name: &str,
    value: &str,
) -> Result<(), DriverError> {
    let mut name_w = to_wide(name);
    let mut val_w = to_wide(value);
    let attr = unsafe {
        CryptCATPutAttrInfo(
            h_cat,
            member,
            name_w.as_mut_ptr(),
            CRYPTCAT_ATTR_AUTHENTICATED | CRYPTCAT_ATTR_NAMEASCII | CRYPTCAT_ATTR_DATAASCII,
            (val_w.len() * 2) as u32,
            val_w.as_mut_ptr() as *mut u8,
        )
    };
    if attr.is_null() {
        Err(last_error("CryptCATPutAttrInfo"))
    } else {
        Ok(())
    }
}

fn self_sign_cat_file(cat_path: &Path, cert_subject: &str) -> Result<(), DriverError> {
    let mut container = to_wide("WinDroidFS_EphemeralKey");

    // Delete any leftover key first
    let mut stale_prov: usize = 0;
    unsafe {
        let _ = CryptAcquireContextW(
            &mut stale_prov,
            container.as_ptr(),
            null(),
            PROV_RSA_AES,
            CRYPT_DELETEKEYSET,
        );
    }

    let mut h_prov: usize = 0;
    if unsafe {
        CryptAcquireContextW(
            &mut h_prov,
            container.as_ptr(),
            null(),
            PROV_RSA_AES,
            CRYPT_NEWKEYSET,
        )
    } == 0
    {
        return Err(last_error("CryptAcquireContextW(NEWKEYSET)"));
    }

    let mut h_key: usize = 0;
    // 0x0800_0000 = 2048-bit RSA key
    if unsafe {
        CryptGenKey(
            h_prov,
            AT_SIGNATURE,
            0x0800_0000 | CRYPT_EXPORTABLE,
            &mut h_key,
        )
    } == 0
    {
        unsafe {
            CryptReleaseContext(h_prov, 0);
            let _ = CryptAcquireContextW(
                &mut stale_prov,
                container.as_ptr(),
                null(),
                PROV_RSA_AES,
                CRYPT_DELETEKEYSET,
            );
        }
        return Err(last_error("CryptGenKey"));
    }

    let result = (|| -> Result<(), DriverError> {
        let subject_w = to_wide(cert_subject);
        let mut name_len = 0u32;
        unsafe {
            CertStrToNameW(
                X509_ASN_ENCODING,
                subject_w.as_ptr(),
                CERT_X500_NAME_STR,
                null(),
                null_mut(),
                &mut name_len,
                null_mut(),
            )
        };
        if name_len == 0 {
            return Err(last_error("CertStrToNameW(size)"));
        }
        let mut name_buf = vec![0u8; name_len as usize];
        if unsafe {
            CertStrToNameW(
                X509_ASN_ENCODING,
                subject_w.as_ptr(),
                CERT_X500_NAME_STR,
                null(),
                name_buf.as_mut_ptr(),
                &mut name_len,
                null_mut(),
            )
        } == 0
        {
            return Err(last_error("CertStrToNameW"));
        }

        let mut subject_blob = CryptoApiBlob {
            cb_data: name_len,
            pb_data: name_buf.as_mut_ptr(),
        };

        let mut key_prov_info = CryptKeyProvInfo {
            pwsz_container_name: container.as_mut_ptr(),
            pwsz_prov_name: null_mut(),
            dw_prov_type: PROV_RSA_AES,
            dw_flags: 0,
            c_prov_param: 0,
            rg_prov_param: null_mut(),
            dw_key_spec: AT_SIGNATURE,
        };

        let mut sig_alg = CryptAlgorithmIdentifier {
            // szOID_RSA_SHA256RSA
            psz_obj_id: b"1.2.840.113549.1.1.11\0".as_ptr() as *mut i8,
            parameters: CryptoApiBlob {
                cb_data: 0,
                pb_data: null_mut(),
            },
        };

        // Encode Code Signing EKU (1.3.6.1.5.5.7.3.3)
        let mut code_signing_oid = b"1.3.6.1.5.5.7.3.3\0".as_ptr() as *mut i8;
        let eku = CertEnhKeyUsage {
            c_usage_identifier: 1,
            rgpsz_usage_identifier: &mut code_signing_oid,
        };
        let mut eku_len = 0u32;
        unsafe {
            CryptEncodeObject(
                X509_ASN_ENCODING,
                X509_ENHANCED_KEY_USAGE,
                &eku as *const _ as *const c_void,
                null_mut(),
                &mut eku_len,
            )
        };
        let mut eku_buf = vec![0u8; eku_len as usize];
        if unsafe {
            CryptEncodeObject(
                X509_ASN_ENCODING,
                X509_ENHANCED_KEY_USAGE,
                &eku as *const _ as *const c_void,
                eku_buf.as_mut_ptr(),
                &mut eku_len,
            )
        } == 0
        {
            return Err(last_error("CryptEncodeObject(EKU)"));
        }

        let mut ext = CertExtension {
            psz_obj_id: b"2.5.29.37\0".as_ptr() as *mut i8, // szOID_ENHANCED_KEY_USAGE
            f_critical: 0,
            value: CryptoApiBlob {
                cb_data: eku_len,
                pb_data: eku_buf.as_mut_ptr(),
            },
        };
        let mut exts = CertExtensions {
            c_extension: 1,
            rg_extension: &mut ext,
        };

        let cert_ctx = unsafe {
            CertCreateSelfSignCertificate(
                h_prov,
                &mut subject_blob,
                0,
                &mut key_prov_info,
                &mut sig_alg,
                null(),
                null(),
                &mut exts,
            )
        };
        if cert_ctx.is_null() {
            return Err(last_error("CertCreateSelfSignCertificate"));
        }

        let sign_res = (|| -> Result<(), DriverError> {
            add_cert_to_machine_store(cert_ctx, "Root")?;
            add_cert_to_machine_store(cert_ctx, "TrustedPublisher")?;
            sign_file_with_cert(cat_path, cert_ctx)
        })();

        unsafe { CertFreeCertificateContext(cert_ctx) };
        sign_res
    })();

    unsafe {
        CryptDestroyKey(h_key);
        CryptReleaseContext(h_prov, 0);
        let _ = CryptAcquireContextW(
            &mut stale_prov,
            container.as_ptr(),
            null(),
            PROV_RSA_AES,
            CRYPT_DELETEKEYSET,
        );
    }

    result
}

fn add_cert_to_machine_store(cert_ctx: *const c_void, store_name: &str) -> Result<(), DriverError> {
    let store_w = to_wide(store_name);
    let h_store = unsafe {
        CertOpenStore(
            10 as *const i8, // CERT_STORE_PROV_SYSTEM_W
            0,
            0,
            CERT_SYSTEM_STORE_LOCAL_MACHINE,
            store_w.as_ptr() as *const c_void,
        )
    };
    if h_store.is_null() {
        return Err(last_error("CertOpenStore"));
    }

    let ok = unsafe {
        CertAddCertificateContextToStore(
            h_store,
            cert_ctx,
            CERT_STORE_ADD_REPLACE_EXISTING,
            null_mut(),
        )
    };
    unsafe { CertCloseStore(h_store, 0) };
    if ok == 0 {
        Err(last_error("CertAddCertificateContextToStore"))
    } else {
        Ok(())
    }
}

fn sign_file_with_cert(cat_path: &Path, cert_ctx: *const c_void) -> Result<(), DriverError> {
    let mssign_w = to_wide("mssign32.dll");
    let h_mod = unsafe { LoadLibraryW(mssign_w.as_ptr()) };
    if h_mod.is_null() {
        return Err(last_error("LoadLibraryW(mssign32.dll)"));
    }

    let sign_fn_ptr = unsafe { GetProcAddress(h_mod, b"SignerSignEx\0".as_ptr()) };
    let free_fn_ptr = unsafe { GetProcAddress(h_mod, b"SignerFreeSignerContext\0".as_ptr()) };
    let Some(sign_fn_ptr) = sign_fn_ptr else {
        unsafe { FreeLibrary(h_mod) };
        return Err(last_error("GetProcAddress(SignerSignEx)"));
    };

    type SignerSignExFn = unsafe extern "system" fn(
        dw_flags: u32,
        p_subject_info: *mut SignerSubjectInfo,
        p_signer_cert: *mut SignerCert,
        p_signature_info: *mut SignerSignatureInfo,
        p_provider_info: *const c_void,
        pwsz_http_time_stamp: *const u16,
        ps_request: *const c_void,
        p_sip_data: *const c_void,
        pp_signer_context: *mut *mut c_void,
    ) -> i32;

    type SignerFreeSignerContextFn =
        unsafe extern "system" fn(p_signer_context: *mut c_void) -> i32;

    let signer_sign_ex: SignerSignExFn = unsafe { std::mem::transmute(sign_fn_ptr) };

    let cat_wide = to_wide(&cat_path.to_string_lossy());
    let mut file_info = SignerFileInfo {
        cb_size: size_of::<SignerFileInfo>() as u32,
        pwsz_file_name: cat_wide.as_ptr(),
        h_file: 0,
    };

    let mut index = 0u32;
    let mut subject_info = SignerSubjectInfo {
        cb_size: size_of::<SignerSubjectInfo>() as u32,
        pdw_index: &mut index,
        dw_subject_choice: 1, // SIGNER_SUBJECT_FILE
        p_signer_file_info: &mut file_info,
    };

    let mut store_info = SignerCertStoreInfo {
        cb_size: size_of::<SignerCertStoreInfo>() as u32,
        p_signing_cert: cert_ctx,
        dw_cert_policy: 2, // SIGNER_CERT_POLICY_CHAIN
        h_cert_store: null_mut(),
    };

    let mut signer_cert = SignerCert {
        cb_size: size_of::<SignerCert>() as u32,
        dw_cert_choice: 2, // SIGNER_CERT_STORE
        p_cert_store_info: &mut store_info,
        hwnd: 0,
    };

    let mut sig_info = SignerSignatureInfo {
        cb_size: size_of::<SignerSignatureInfo>() as u32,
        algid_hash: CALG_SHA_256,
        dw_attr_choice: 0, // SIGNER_NO_ATTR
        p_attr_authcode: null_mut(),
        ps_authenticated: null_mut(),
        ps_unauthenticated: null_mut(),
    };

    let mut signer_ctx: *mut c_void = null_mut();
    let hr = unsafe {
        signer_sign_ex(
            0,
            &mut subject_info,
            &mut signer_cert,
            &mut sig_info,
            null(),
            null(),
            null(),
            null(),
            &mut signer_ctx,
        )
    };

    if !signer_ctx.is_null() {
        if let Some(free_ptr) = free_fn_ptr {
            let free_fn: SignerFreeSignerContextFn = unsafe { std::mem::transmute(free_ptr) };
            unsafe { free_fn(signer_ctx) };
        }
    }
    unsafe { FreeLibrary(h_mod) };

    if hr < 0 {
        Err(DriverError::Win32 {
            call: "SignerSignEx",
            code: hr as u32,
        })
    } else {
        Ok(())
    }
}

fn stage_inf_into_store(inf_path: &Path, source_dir: &Path) -> Result<String, DriverError> {
    let inf_w = to_wide(&inf_path.to_string_lossy());
    let dir_w = to_wide(&source_dir.to_string_lossy());
    let mut dest_buf = [0u16; 260];
    let mut fname_ptr: *mut u16 = null_mut();

    let ok = unsafe {
        SetupCopyOEMInfW(
            inf_w.as_ptr(),
            dir_w.as_ptr(),
            SPOST_PATH,
            0,
            dest_buf.as_mut_ptr(),
            dest_buf.len() as u32,
            null_mut(),
            &mut fname_ptr,
        )
    };
    if ok == 0 {
        return Err(last_error("SetupCopyOEMInfW"));
    }

    let len = dest_buf
        .iter()
        .position(|&c| c == 0)
        .unwrap_or(dest_buf.len());
    let full_oem_path = PathBuf::from(String::from_utf16_lossy(&dest_buf[..len]));
    Ok(full_oem_path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default())
}

